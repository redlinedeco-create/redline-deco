param(
  [string]$Root = "public\images"
)

$lines = New-Object System.Collections.ArrayList
[void]$lines.Add('// AUTO-GENERATED by scripts/gen-photo-pool.ps1 - do not edit by hand.')
[void]$lines.Add('// Sliced by data/projects.ts so every photo belongs to exactly one project.')
[void]$lines.Add('')
[void]$lines.Add('export const photoPool = {')

foreach ($dir in Get-ChildItem -Path $Root -Directory | Sort-Object Name) {
  $files = @(Get-ChildItem -Path $dir.FullName -File -Filter *.jpg | Sort-Object Name)
  if ($files.Count -eq 0) { continue }
  [void]$lines.Add(('  "{0}": [' -f $dir.Name))
  foreach ($f in $files) {
    [void]$lines.Add(('    "/images/{0}/{1}",' -f $dir.Name, $f.Name))
  }
  [void]$lines.Add('  ],')
}

[void]$lines.Add('} satisfies Record<string, string[]>;')
[void]$lines.Add('')
[void]$lines.Add('export type PhotoFolder = keyof typeof photoPool;')
[void]$lines.Add('')

$out = Join-Path (Split-Path -Parent $PSScriptRoot) "data\photoPool.ts"
$lines -join "`n" | Set-Content -Path $out -Encoding utf8

$count = (Get-ChildItem -Path $Root -Recurse -File -Filter *.jpg).Count
Write-Host "wrote data/photoPool.ts containing $count jpg paths"
