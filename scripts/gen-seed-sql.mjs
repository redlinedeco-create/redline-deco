/**
 * Generates supabase/seed.sql from the bundled data/*.ts files.
 *
 *   node scripts/gen-seed-sql.mjs
 *
 * Uses the TypeScript compiler to load the data modules, then emits INSERT
 * statements for the tables the site reads at runtime: categories, services,
 * prices, testimonials, projects and media.
 *
 * site_text and settings are intentionally skipped -- nothing calls
 * lib/content.ts's getSiteText() or getSettings() yet, and the UI copy still
 * comes from lib/i18n.ts.
 */

import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createRequire } from "node:module";
import ts from "typescript";

const ROOT = process.cwd();
const TMP = join(ROOT, ".seed-tmp");
const OUT = join(ROOT, "supabase", "seed.sql");

const MODULES = [
  "data/photoPool.ts",
  "data/projects.ts",
  "data/categories.ts",
  "data/services.ts",
  "data/pricing.ts",
  "data/testimonials.ts",
];

/** "/images/painting/x.jpg" -> "painting/x.jpg" */
const toStoragePath = (src) =>
  src
    .replace(/^https?:\/\/[^/]+\/storage\/v1\/object\/public\/[^/]+\//, "")
    .replace(/^\/images\//, "");

/**
 * prices.category and projects.category are FKs to categories.slug, but the
 * bundled pricing data groups prices under its own labels that predate the
 * categories table. Map them onto real slugs.
 */
const PRICE_CATEGORY_SLUG = {
  "peinture-applications": "painting",
  "esthetique-lumiere": "decorative",
  "placoplatre-pvc": "drywall",
};

const q = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return Number.isFinite(v) ? String(v) : "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v)) return `array[${v.map(q).join(",")}]::text[]`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

/** jsonb column: keeps only the languages that have copy. */
const jb = (v) => {
  if (!v || typeof v !== "object") return "null";
  const out = {};
  for (const l of ["en", "fr", "ar"]) {
    const text = v[l];
    if (typeof text === "string" && text.trim()) out[l] = text;
  }
  return Object.keys(out).length
    ? `'${JSON.stringify(out).replace(/'/g, "''")}'::jsonb`
    : "null";
};

function loadModules() {
  rmSync(TMP, { recursive: true, force: true });

  // Mirrors the data/ layout so relative imports like "./photoPool" still
  // resolve once the files are emitted as CommonJS.
  for (const rel of MODULES) {
    const source = readFileSync(join(ROOT, rel), "utf8");
    const js = ts.transpileModule(source, {
      compilerOptions: {
        module: ts.ModuleKind.CommonJS,
        target: ts.ScriptTarget.ES2020,
      },
      fileName: rel,
    }).outputText;

    const dest = join(TMP, rel.replace(/\.ts$/, ".js"));
    mkdirSync(join(dest, ".."), { recursive: true });
    writeFileSync(dest, js, "utf8");
  }

  const require = createRequire(join(TMP, "index.js"));
  const load = (rel) => require("./" + rel.replace(/\.ts$/, ".js"));

  return {
    projects: load("data/projects.ts").projects,
    categories: load("data/categories.ts").categories,
    services: load("data/services.ts").services,
    pricing: load("data/pricing.ts").pricing,
    testimonials: load("data/testimonials.ts").testimonials,
  };
}

function main() {
  const d = loadModules();

  // Both category columns are FKs to categories.slug. Catch a bad value here
  // rather than letting the whole transaction fail on the server.
  const slugs = new Set(d.categories.map((c) => c.slug));
  const badPrices = [
    ...new Set(
      d.pricing
        .map((p) => PRICE_CATEGORY_SLUG[p.category] ?? p.category)
        .filter((s) => !slugs.has(s)),
    ),
  ];
  const badProjects = [
    ...new Set(d.projects.map((p) => p.category).filter((s) => !slugs.has(s))),
  ];
  if (badPrices.length || badProjects.length) {
    console.error("FK violation before sending to Postgres:");
    if (badPrices.length) console.error("  prices.category: " + badPrices.join(", "));
    if (badProjects.length) console.error("  projects.category: " + badProjects.join(", "));
    console.error("  known category slugs: " + [...slugs].join(", "));
    process.exit(1);
  }

  const sql = [];

  sql.push("-- Generated by scripts/gen-seed-sql.mjs -- do not edit by hand.");
  sql.push("-- Source of truth for these rows is data/*.ts.");
  sql.push("-- Idempotent: re-running overwrites by primary key.");
  sql.push("");

  sql.push("begin;");
  sql.push("");

  sql.push("-- categories");
  sql.push(
    `insert into categories (id, slug, name, description, sort_order) values`,
  );
  sql.push(
    d.categories
      .map(
        (c, i) =>
          `  (${q(c.id)}, ${q(c.slug)}, ${jb(c.name)}, ${jb(c.description)}, ${i})`,
      )
      .join(",\n") +
    "\non conflict (id) do update set" +
    "\n  slug = excluded.slug, name = excluded.name," +
    "\n  description = excluded.description, sort_order = excluded.sort_order;",
  );
  sql.push("");

  sql.push("-- services");
  sql.push(
    `insert into services (id, name, description, icon, starting_price, unit, sort_order) values`,
  );
  sql.push(
    d.services
      .map(
        (s, i) =>
          `  (${q(s.id)}, ${jb(s.name)}, ${jb(s.description)}, ${q(s.icon)}, ${
            s.startingPrice ?? "null"
          }, ${jb(s.unit)}, ${i})`,
      )
      .join(",\n") +
    "\non conflict (id) do update set" +
    "\n  name = excluded.name, description = excluded.description, icon = excluded.icon," +
    "\n  starting_price = excluded.starting_price, unit = excluded.unit, sort_order = excluded.sort_order;",
  );
  sql.push("");

  sql.push("-- prices");
  sql.push(
    `insert into prices (id, service, category, description, unit, price_from, price_to, currency, notes, sort_order) values`,
  );
  sql.push(
    d.pricing
      .map(
        (p, i) =>
          `  (${q(p.id)}, ${jb(p.service)}, ${q(PRICE_CATEGORY_SLUG[p.category] ?? p.category)}, ${jb(
            p.description,
          )}, ${jb(p.unit)}, ${p.priceFrom}, ${
            p.priceTo ?? "null"
          }, ${q(p.currency)}, ${jb(p.notes)}, ${i})`,
      )
      .join(",\n") +
    "\non conflict (id) do update set" +
    "\n  service = excluded.service, category = excluded.category, description = excluded.description," +
    "\n  unit = excluded.unit, price_from = excluded.price_from, price_to = excluded.price_to," +
    "\n  currency = excluded.currency, notes = excluded.notes, sort_order = excluded.sort_order;",
  );
  sql.push("");
  sql.push("");

  sql.push("-- testimonials");
  sql.push(
    `insert into testimonials (id, name, project, review, rating, review_date, photo_path, is_placeholder, sort_order) values`,
  );
  sql.push(
    d.testimonials
      .map(
        (t, i) =>
          `  (${q(t.id)}, ${q(t.name)}, ${q(t.project ?? null)}, ${jb(t.review)}, ${
            t.rating ?? "null"
          }, ${q(t.date ?? null)}, ${q(
            t.photo ? toStoragePath(t.photo) : null,
          )}, ${t.isPlaceholder === false ? "false" : "true"}, ${i})`,
      )
      .join(",\n") +
    "\non conflict (id) do update set" +
    "\n  name = excluded.name, project = excluded.project, review = excluded.review," +
    "\n  rating = excluded.rating, review_date = excluded.review_date, photo_path = excluded.photo_path," +
    "\n  is_placeholder = excluded.is_placeholder, sort_order = excluded.sort_order;",
  );
  sql.push("");

  // projects must come last: category is a FK to categories.slug.
  sql.push("-- projects");
  sql.push(
    `insert into projects (id, slug, title, category, location, description, services, year, cover_path, images, before_path, after_path, featured, sort_order, created_at) values`,
  );
  sql.push(
    d.projects
      .map(
        (p, i) =>
          `  (${q(p.id)}, ${q(p.slug)}, ${jb(p.title)}, ${q(p.category)}, ${jb(
            p.location,
          )}, ${jb(p.description)}, ${q(p.services)}, ${p.year}, ${q(
            toStoragePath(p.coverImage),
          )}, ${q(p.images.map(toStoragePath))}, ${q(
            p.beforeImage ? toStoragePath(p.beforeImage) : null,
          )}, ${q(
            p.afterImage ? toStoragePath(p.afterImage) : null,
          )}, ${p.featured ? "true" : "false"}, ${i}, ${q(p.createdAt)})`,
      )
      .join(",\n") +
    "\non conflict (id) do update set" +
    "\n  slug = excluded.slug, title = excluded.title, category = excluded.category," +
    "\n  location = excluded.location, description = excluded.description, services = excluded.services," +
    "\n  year = excluded.year, cover_path = excluded.cover_path, images = excluded.images," +
    "\n  before_path = excluded.before_path, after_path = excluded.after_path," +
    "\n  featured = excluded.featured, sort_order = excluded.sort_order;",
  );
  sql.push("");

  // Media rows are derived from the bucket itself rather than transcribed, so
  // mime type and byte size always match what was actually uploaded. Requires
  // scripts/upload-photos.mjs to have run first.
  sql.push("-- media library rows, derived from the uploaded bucket contents");
  sql.push(`insert into media (path, filename, mime, size_bytes, folder, created_at)`);
  sql.push(`select`);
  sql.push(`  o.name,`);
  sql.push(`  split_part(o.name, '/', -1),`);
  sql.push(`  coalesce(o.metadata->>'mimetype', ''),`);
  sql.push(`  nullif(o.metadata->>'size', '')::bigint,`);
  sql.push(`  nullif(split_part(o.name, '/', 1), o.name),`);
  sql.push(`  o.created_at`);
  sql.push(`from storage.objects o`);
  sql.push(`where o.bucket_id = 'media'`);
  sql.push(`on conflict (path) do update set`);
  sql.push(`  filename = excluded.filename,`);
  sql.push(`  mime = excluded.mime,`);
  sql.push(`  size_bytes = excluded.size_bytes,`);
  sql.push(`  folder = excluded.folder;`);
  sql.push("");

  sql.push("commit;");

  writeFileSync(OUT, sql.join("\n") + "\n", "utf8");

  console.log(`Wrote ${OUT}`);
  console.log(
    `  categories=${d.categories.length} services=${d.services.length} prices=${d.pricing.length} testimonials=${d.testimonials.length} projects=${d.projects.length}`,
  );
}

main();